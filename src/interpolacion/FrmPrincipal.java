    private void btn_CargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CargarDatosActionPerformed
        // TODO add your handling code here:
        //-------------------------------------
        /**llamamos el metodo que permite cargar la ventana*/
        TxtDatos.setText(null);
        TxtDatos.setText(" ");
        TxtDI.setText(" ");
        arrayx.clear();
        arrayy.clear();
        

       

        try {
            //Carga el archivo con los valores

            /**llamamos el metodo que permite cargar la ventana*/
            JFileChooser explorador=new JFileChooser("home");

            //Le cambiamos el titulo
            explorador.setDialogTitle("Cargar datos...");

            //Agregamos un filtro de extensiones
            explorador.setFileFilter(new FileNameExtensionFilter("txt - Archivo de texto", "txt"));
            explorador.showOpenDialog(this);
            /**abrimos el archivo seleccionado*/
            File abre=explorador.getSelectedFile();

            /**recorremos el archivo, lo leemos para plasmarlo
            *en el area de texto*/
            if(abre!=null)
            {

                FileReader archivos=new FileReader(abre);

                BufferedReader in = new BufferedReader(archivos);
                
                
                
                String str = in.readLine();
                while ((str = in.readLine()) != null) {
                    String[] values = str.split(" ");//Busca en la linea de entrada, 
                    //el espacio en blanco " " como separador para determinar el 
                    //valor de x Y de y

                    arrayx.add(Double.parseDouble(values[0]));//Se llena el vector x
                    arrayy.add(Double.parseDouble(values[1]));//Se llena el vector y

                }
                in.close();//Se cierra el archivo
                
                
                for (int i=0;i<arrayx.size();i++)
                {
                    TxtDatos.append("x = "+arrayx.get(i).toString() +" y = "+arrayy.get(i).toString()+"\n");//Imprime el número de horas extras dominicales y festivos.
                }

            }//Fin if abre
            else
            {
                JOptionPane.showMessageDialog(null, "No se pudo abrir el archivo.");

            }
        }//fin try
        catch(IOException ex)
        {
            JOptionPane.showMessageDialog(null,ex+"" +
                "\nNo se ha encontrado el archivo",
                "ADVERTENCIA!!!",JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btn_CargarDatosActionPerformed

