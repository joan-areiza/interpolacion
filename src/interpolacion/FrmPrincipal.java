    private void btn_GraficarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_GraficarActionPerformed
        // TODO add your handling code here:

        Graficas migrafica = new  Graficas(Graficas.LINEAL,"Interpolación polinomial método de Lagrange", "x", "y=f(x)");
        double [] vectorX=new double[arrayx.size()];
        double [] vectorY=new double[arrayy.size()];
        for (int i=0;i<arrayx.size();i++)
        {
            vectorX[i]=arrayx.get(i);
            vectorY[i]=arrayy.get(i);
        }

        migrafica.agregarGrafica("Polinomio de interpolación", vectorX, vectorY);

        JPanel panel=migrafica.obtienePanel();
        migrafica.setSize(600, 600);

        migrafica.add(panel);
        migrafica.setVisible(true);
    }//GEN-LAST:event_btn_GraficarActionPerformed

    private void btn_CalcYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CalcYActionPerformed
        // TODO add your handling code here:

        x=Double.parseDouble(Txt_x.getText());
        //Primer ciclo del cálculo polinomial
        for(int count = 0; count<arrayx.size(); count++)
        {

            //Inicialización de las variables
            numerador = 1; denominador = 1;

            //Segundo ciclo de el cálculo polinomial
            for(int count2 = 0; count2<arrayx.size(); count2++)
            {
                if (count2 != count)
                {
                    numerador = numerador * (x - arrayx.get(count2));
                    denominador = denominador * (arrayx.get(count) - arrayx.get(count2));
                }
            }
            y = y + (numerador/denominador) * arrayy.get(count);
        }

       // System.out.println("Para x = " + x + "," + " y = " +  y);
        Txt_y.setText(String.valueOf(y));

        //Se agregan los nuevos valores a los vectores existentes
        arrayx.add(x);//Se llena el vector x
        arrayy.add(y);//Se llena el vector y
        //Se ordenan los vectores con los nuevos valores
        Collections.sort(arrayx);
        Collections.sort(arrayy);
        TxtDatosInterpolados.setText(null);
        TxtDI.setText(null);
        TxtDI.append(arrayx.get(0).toString() +" "+arrayy.get(0).toString()+"\n");
        //Se imprimen los vectores en el
        for (int i=0;i<arrayx.size();i++)
        {
            TxtDatosInterpolados.append("x = "+arrayx.get(i).toString() +" y = "+arrayy.get(i).toString()+"\n");
            TxtDI.append(arrayx.get(i).toString() +" "+arrayy.get(i).toString()+"\n");
        }
    }//GEN-LAST:event_btn_CalcYActionPerformed

